#!/usr/bin/env python3
"""Extract the build substance of the Phase A plan into smaller derived files.

`docs/plans/plan-phase-a.md` mixes what to build with the records of how the
plan was produced: claim verification, collapse tests, question registers,
coverage tables, per-step justification. This script writes read-only views
that keep only what to build. It never modifies the source plan; the full
plan remains the record, and the derived files are regenerated from it.

    python3 middleware/context-oracle/tools/extract_plan_core.py OUT_DIR

Outputs, written to OUT_DIR (overwritten on every run):
  plan-phase-a-core.md   goal, scope, the 40 steps (build parts only)
  plan-phase-a-tests.md  section 12 test specifications, unchanged

OUT_DIR should be outside docs/: the outputs are derived views, and a second
committed copy of plan content would break this project's one-fact-one-home
rule (CLAUDE.md, "Where information goes").

What is kept and dropped is declared in KEEP_SECTIONS / TEST_SECTIONS and
STEP_DROP_LABELS below; every dropped region is counted in the printed report.
"""
from __future__ import annotations

import hashlib
import re
import sys
from pathlib import Path

PROJECT = Path(__file__).resolve().parent.parent
SOURCE = PROJECT / "docs/plans/plan-phase-a.md"

# Section numbers (from "## N." / "### N.M" headings) whose content is kept.
# Anything not listed is a record of the planning process and is dropped:
# 2.3/2.4 coverage tables, 3 standards (the spec's section 9 governs), 4 spec
# issues, 5 file listings (each step's step-decl block carries its files),
# 6 foundation corrections, 8 divergences, 9 checkpoints, 10/10A decisions and
# collapse tests, 11 claim verification, 13 risks, 14 question register.
# Kept beyond the steps: 15 open gaps (what is unresolved) and 16 the
# post-completion acceptance check (what done means).
KEEP_SECTIONS = {"1", "2.1", "2.2", "7", "15", "16"}
TEST_SECTIONS = {"12"}

# Inside a step, a paragraph opening with one of these labels starts a region
# of justification or provenance, dropped until the next step label. Build
# parts (What changes, Creates, Dependencies, Verification, Reopened ... build
# delta) and the step-decl block are kept.
STEP_DROP_LABELS = ("**Source.**", "**Impact if wrong.**", "**Why this approach")
STEP_KEEP_LABELS = ("**What changes.**", "**Creates.**", "**Dependencies.**",
                    "**Verification.**", "**Reopened ")

H2 = re.compile(r"^## (\d+[A-Z]?)\.?\s")
H3 = re.compile(r"^### (\d+(?:\.\d+)?)\s")
STEP = re.compile(r"^### Step \d+\b")


def section_of(h2: str, h3: str | None) -> str:
    return h3 if h3 and h3.split(".")[0] == h2 else h2


def selected(sec: str, wanted: set[str]) -> bool:
    return sec in wanted or sec.split(".")[0] in wanted


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    out_dir = Path(sys.argv[1]).resolve()
    out_dir.mkdir(parents=True, exist_ok=True)
    core_out = out_dir / "plan-phase-a-core.md"
    tests_out = out_dir / "plan-phase-a-tests.md"
    raw = SOURCE.read_bytes()
    lines = raw.decode("utf-8").splitlines()
    digest = hashlib.sha256(raw).hexdigest()[:12]

    core: list[str] = []
    tests: list[str] = []
    dropped: dict[str, int] = {}
    h2 = h3 = None
    in_fence = False
    step_mode_keep = True

    # Title line (before the first "## ") is kept in core.
    for line in lines:
        if not in_fence:
            m2, m3 = H2.match(line), H3.match(line)
            if m2:
                h2, h3 = m2.group(1), None
                step_mode_keep = True
            elif m3:
                h3 = m3.group(1)
            if STEP.match(line):
                step_mode_keep = True
        if line.startswith("```"):
            in_fence = not in_fence

        if h2 is None:
            core.append(line)
            continue
        sec = section_of(h2, h3)

        if selected(sec, TEST_SECTIONS):
            tests.append(line)
            continue
        if not selected(sec, KEEP_SECTIONS):
            dropped[f"section {sec}"] = dropped.get(f"section {sec}", 0) + 1
            continue

        if h2 == "7" and not in_fence:
            stripped = line.lstrip()
            if stripped.startswith(STEP_DROP_LABELS):
                step_mode_keep = False
            elif stripped.startswith(STEP_KEEP_LABELS):
                step_mode_keep = True
        if h2 == "7" and not step_mode_keep:
            dropped["step justification (Source / Impact if wrong / Why)"] = \
                dropped.get("step justification (Source / Impact if wrong / Why)", 0) + 1
            continue
        core.append(line)

    header = [
        "<!-- GENERATED by middleware/context-oracle/tools/extract_plan_core.py "
        f"from docs/plans/plan-phase-a.md (sha256 {digest}). Do not edit; edit "
        "the full plan and regenerate. Dropped regions are planning records and "
        "per-step justification; they remain in the full plan. -->",
        "",
    ]
    core_out.write_text("\n".join(header + core).rstrip() + "\n", encoding="utf-8")
    tests_out.write_text("\n".join(header + tests).rstrip() + "\n", encoding="utf-8")

    print(f"source  {len(lines):>6} lines  {SOURCE.relative_to(PROJECT)}")
    print(f"core    {len(core):>6} lines  {core_out}")
    print(f"tests   {len(tests):>6} lines  {tests_out}")
    print("dropped:")
    for k, v in sorted(dropped.items(), key=lambda kv: -kv[1]):
        print(f"  {v:>6}  {k}")
    total = len(core) + len(tests) + sum(dropped.values())
    if total != len(lines):
        print(f"line accounting mismatch: {total} != {len(lines)}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env node
// Generates docs/defects/README.md from the defect files' own frontmatter.
//
// The index is GENERATED, never hand-maintained. This repo's measured history is that a
// hand-maintained index of derived data drifts and becomes the regression engine in its own
// fix loop; the only thing that has ever closed that class here is generating the derived
// surface instead of checking it harder.
//
// Usage:
//   node scripts/derive-defect-index.mjs           rewrite the index
//   node scripts/derive-defect-index.mjs --check   exit 1 if the index is stale (for the tier)

import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs'
import { join, dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
export const DEFECTS_DIR = join(ROOT, 'docs', 'defects')
export const INDEX_PATH = join(DEFECTS_DIR, 'README.md')

// Order is the reading order of the index, and the ranking a reader should apply.
export const SEVERITIES = ['critical', 'serious', 'moderate', 'minor']
export const STATES = ['open', 'investigating', 'corrected']

export function parseFrontmatter(text) {
  const m = /^---\n([\s\S]*?)\n---/.exec(text.replace(/\r\n/g, '\n'))
  if (!m) return null
  const out = {}
  for (const line of m[1].split('\n')) {
    const kv = /^([a-z_]+):\s*(.*)$/.exec(line)
    if (kv) out[kv[1]] = kv[2].trim()
  }
  return out
}

export function collect(dir = DEFECTS_DIR) {
  if (!existsSync(dir)) return []
  return readdirSync(dir)
    .filter((f) => f.endsWith('.md') && f !== 'README.md')
    .map((f) => {
      const fm = parseFrontmatter(readFileSync(join(dir, f), 'utf8'))
      if (!fm || !fm.id) throw new Error(`${f}: missing or unparseable frontmatter (id required)`)
      if (!SEVERITIES.includes(fm.severity)) throw new Error(`${f}: severity must be one of ${SEVERITIES.join(', ')}`)
      if (!STATES.includes(fm.state)) throw new Error(`${f}: state must be one of ${STATES.join(', ')}`)
      return { ...fm, file: f }
    })
    .sort((a, b) =>
      SEVERITIES.indexOf(a.severity) - SEVERITIES.indexOf(b.severity) || a.id.localeCompare(b.id))
}

export function render(defects) {
  const open = defects.filter((d) => d.state !== 'corrected')
  const byState = (s) => defects.filter((d) => d.state === s).length
  const bySev = (s) => open.filter((d) => d.severity === s).length

  const rows = defects.map((d) => {
    const state = d.state === 'corrected' ? `corrected (${d.fixed_in || 'unrecorded'})` : d.state
    return `| [${d.id}](${d.file}) | ${d.severity} | ${state} | ${d.title} | \`${d.component}\` |`
  })

  return [
    '<!-- GENERATED by scripts/derive-defect-index.mjs — do not edit by hand. -->',
    '<!-- Edit a defect file, then re-run the script. The tier checks this file is current. -->',
    '',
    '# Open defects — expert-dev-tools',
    '',
    'Standing queue of defects in **this plugin**. One file per defect; this index is',
    'generated from their frontmatter.',
    '',
    `**${open.length} open** — ${SEVERITIES.map((s) => `${bySev(s)} ${s}`).join(', ')}.`,
    `${byState('investigating')} being investigated, ${byState('corrected')} corrected.`,
    '',
    '## How a defect gets here',
    '',
    'Anything wrong with the plugin itself: a crash, a control that fires wrongly, a contract',
    'that cannot be satisfied honestly, a behavior the owner has rejected. Add a file with the',
    'frontmatter below and re-run the generator. Report the observed behavior and the evidence',
    'for it; do not write a guessed fix into the record — diagnosis is a dispatched role with',
    'its own verification duties, and a wrong entry here is read as established for years.',
    '',
    'Do not patch the plugin to get past a defect. File it.',
    '',
    '```yaml',
    'id: EDT-nnnn            # next free number',
    'title: one line, observed behavior',
    `state: ${STATES.join(' | ')}`,
    `severity: ${SEVERITIES.join(' | ')}`,
    'component: the file or contract whose behavior is wrong',
    'found_in_version: 0.4.1',
    'found_by: where it was observed, with a run or session identifier',
    'fixed_in: null         # a version, once corrected',
    '```',
    '',
    '## How a defect leaves',
    '',
    "Through the plugin's own correction process — remediation plan, review rounds,",
    'implementation, version bump, commit. Not by hand-editing the workflow. Set `state:',
    'corrected` and `fixed_in:` to the version that shipped the fix, and re-run the generator.',
    '',
    '## The queue',
    '',
    '| id | severity | state | what | component |',
    '|---|---|---|---|---|',
    ...rows,
    '',
  ].join('\n')
}

function main() {
  const check = process.argv.includes('--check')
  const defects = collect()
  const next = render(defects)
  const current = existsSync(INDEX_PATH) ? readFileSync(INDEX_PATH, 'utf8').replace(/\r\n/g, '\n') : ''
  if (check) {
    if (current !== next) {
      process.stderr.write('defect index is stale — run: node scripts/derive-defect-index.mjs\n')
      process.exit(1)
    }
    process.stdout.write(`defect index current (${defects.length} defects)\n`)
    process.exit(0)
  }
  writeFileSync(INDEX_PATH, next, 'utf8')
  process.stdout.write(`wrote ${INDEX_PATH} (${defects.length} defects)\n`)
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) main()
